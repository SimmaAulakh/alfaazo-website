/**
 * Regenerates lib/admin/lessonCatalog.ts from the app's lesson catalog so the
 * admin console can show lesson titles, units, sections and course order.
 *
 *   node scripts/sync-lesson-catalog.mjs [path/to/punjabi_lingo]
 *
 * Default app path: ../punjabi_lingo next to this repo. Run it whenever lessons
 * or units change in the app. Lessons missing from the map still show in the
 * admin, just under a name derived from their id.
 */
import fs from "node:fs";
import path from "node:path";

// Mirrors HubTheme.sectionTitle in the app (lib/theme/lessons_hub_theme.dart).
const SECTION_TITLES = { 1: "The Foundations", 2: "Tell Your Story" };
const sectionTitle = (n) => SECTION_TITLES[n] ?? `Section ${n}`;

const appDir = path.resolve(process.argv[2] ?? path.join(process.cwd(), "..", "punjabi_lingo"));
const catalog = JSON.parse(fs.readFileSync(path.join(appDir, "assets", "data", "lessons.json"), "utf8"));
const byId = new Map(catalog.lessons.map((l) => [l.id, l]));

const units = catalog.units.map((u, i) => {
  // The app's UnitModel defaults section to 1 when lessons.json omits it.
  const section = Number.isInteger(u.section) ? u.section : 1;
  return { id: u.id, number: i + 1, title: u.title, section, sectionTitle: sectionTitle(section), lessonIds: u.lessonIds };
});
const lessons = units.flatMap((u) =>
  u.lessonIds.map((id) => ({
    id,
    title: byId.get(id)?.title ?? id,
    unit: u.number,
    unitTitle: u.title,
    section: u.section,
  })),
);
const sections = [...new Set(units.map((u) => u.section))].map((n) => ({
  number: n,
  title: sectionTitle(n),
  unitIds: units.filter((u) => u.section === n).map((u) => u.id),
  lessonCount: units.filter((u) => u.section === n).reduce((k, u) => k + u.lessonIds.length, 0),
}));

const out = `// GENERATED by scripts/sync-lesson-catalog.mjs from punjabi_lingo
// assets/data/lessons.json — do not edit by hand. Re-run the script when the
// app's lessons change. ${lessons.length} lessons in ${units.length} units and ${sections.length} sections, in course order.

export interface CatalogLesson {
  id: string;
  title: string;
  /** 1-based unit number. */
  unit: number;
  unitTitle: string;
  section: number;
}

export interface CatalogUnit {
  id: string;
  /** 1-based position in the course. */
  number: number;
  title: string;
  section: number;
  sectionTitle: string;
  lessonIds: string[];
}

export interface CatalogSection {
  number: number;
  title: string;
  unitIds: string[];
  lessonCount: number;
}

export const LESSON_CATALOG: CatalogLesson[] = ${JSON.stringify(lessons, null, 2)};

export const UNIT_CATALOG: CatalogUnit[] = ${JSON.stringify(units, null, 2)};

export const SECTION_CATALOG: CatalogSection[] = ${JSON.stringify(sections, null, 2)};
`;
fs.writeFileSync(path.join(process.cwd(), "lib", "admin", "lessonCatalog.ts"), out);
console.log(`lessonCatalog.ts: ${lessons.length} lessons, ${units.length} units, ${sections.length} sections`);
