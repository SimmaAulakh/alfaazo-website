/**
 * Regenerates lib/admin/lessonCatalog.ts from the app's lesson catalog so the
 * admin console can show lesson titles, units and course order.
 *
 *   node scripts/sync-lesson-catalog.mjs [path/to/punjabi_lingo]
 *
 * Default app path: ../punjabi_lingo next to this repo. Run it whenever lessons
 * are added in the app. Lessons missing from the map still show in the admin,
 * just under a name derived from their id.
 */
import fs from "node:fs";
import path from "node:path";

const appDir = path.resolve(process.argv[2] ?? path.join(process.cwd(), "..", "punjabi_lingo"));
const src = path.join(appDir, "assets", "data", "lessons.json");
const catalog = JSON.parse(fs.readFileSync(src, "utf8"));
const byId = new Map(catalog.lessons.map((l) => [l.id, l]));

const entries = [];
catalog.units.forEach((u, ui) => {
  u.lessonIds.forEach((id) => {
    const l = byId.get(id);
    entries.push({ id, title: l?.title ?? id, unit: ui + 1, unitTitle: u.title });
  });
});

const out = `// GENERATED by scripts/sync-lesson-catalog.mjs from punjabi_lingo
// assets/data/lessons.json — do not edit by hand. Re-run the script when the
// app's lessons change. ${entries.length} lessons in ${catalog.units.length} units, in course order.

export interface CatalogLesson {
  id: string;
  title: string;
  /** 1-based unit number. */
  unit: number;
  unitTitle: string;
}

export const LESSON_CATALOG: CatalogLesson[] = ${JSON.stringify(entries, null, 2)};
`;
const dest = path.join(process.cwd(), "lib", "admin", "lessonCatalog.ts");
fs.writeFileSync(dest, out);
console.log(`lessonCatalog.ts: ${entries.length} lessons in ${catalog.units.length} units`);
